#!/usr/bin/env bash
# STEP 6 (optional): installs and starts Langfuse (tracing of your agents' calls).
#
#     ./6-langfuse.sh
#
# - clones the official langfuse/langfuse repository into langfuse/app (official docker-compose.yml)
# - generates all the secrets in langfuse/app/.env (hidden file, never overwritten)
# - creates in advance the organisation, the project, your account and the API keys (LANGFUSE_INIT_* variables)
# - starts Langfuse: http://127.0.0.1:3002
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/langfuse"

for c in docker git openssl curl; do
  command -v "$c" >/dev/null 2>&1 || { echo "'$c' is missing (sudo apt install $c)." >&2; exit 1; }
done
docker info >/dev/null 2>&1 || { echo "Docker does not answer (see ./1-prerequis.sh)." >&2; exit 1; }
docker network inspect obs-net >/dev/null 2>&1 || {
  echo "The obs-net network does not exist: update ai-stack then run 'docker compose up -d' in it again." >&2; exit 1; }

if [ ! -d app/.git ]; then
  echo "→ Downloading the official Langfuse repository..."
  git clone --depth 1 https://github.com/langfuse/langfuse.git app
fi
cp docker-compose.override.yml app/docker-compose.override.yml

if [ ! -f app/.env ]; then
  echo "→ Generating the secrets (app/.env)..."
  r() { openssl rand -hex "$1"; }
  PG="$(r 24)"; MINIO="$(r 24)"
  umask 077
  cat > app/.env <<ENV
# Generated by 6-langfuse.sh. Do not share. Back it up.
POSTGRES_PASSWORD=${PG}
DATABASE_URL=postgresql://postgres:${PG}@postgres:5432/postgres
SALT=$(r 24)
ENCRYPTION_KEY=$(r 32)
CLICKHOUSE_PASSWORD=$(r 24)
REDIS_AUTH=$(r 24)
NEXTAUTH_SECRET=$(r 32)
NEXTAUTH_URL=http://localhost:3002
MINIO_ROOT_PASSWORD=${MINIO}
LANGFUSE_S3_EVENT_UPLOAD_SECRET_ACCESS_KEY=${MINIO}
LANGFUSE_S3_MEDIA_UPLOAD_SECRET_ACCESS_KEY=${MINIO}
LANGFUSE_S3_BATCH_EXPORT_SECRET_ACCESS_KEY=${MINIO}
LANGFUSE_S3_MEDIA_UPLOAD_ENDPOINT=http://localhost:9092

# Automatic creation of the organisation, the project, the account and the API keys
LANGFUSE_INIT_ORG_ID=lab
LANGFUSE_INIT_ORG_NAME=Lab
LANGFUSE_INIT_PROJECT_ID=ai-lab
LANGFUSE_INIT_PROJECT_NAME=AI Lab
LANGFUSE_INIT_PROJECT_PUBLIC_KEY=pk-lf-$(r 16)
LANGFUSE_INIT_PROJECT_SECRET_KEY=sk-lf-$(r 16)
LANGFUSE_INIT_USER_EMAIL=admin@lab.local
LANGFUSE_INIT_USER_NAME=admin
LANGFUSE_INIT_USER_PASSWORD=$(r 12)
ENV
  chmod 600 app/.env
else
  echo "• app/.env already exists: left untouched."
fi

echo "→ Starting Langfuse (first start: several minutes)..."
(cd app && docker compose up -d)

echo -n "→ Waiting for Langfuse to answer"
for _ in $(seq 1 90); do
  if curl -fsS http://127.0.0.1:3002/api/public/health >/dev/null 2>&1; then ok=1; break; fi
  echo -n "."; sleep 5
done
echo
[ "${ok:-0}" = 1 ] || { echo "Langfuse is not answering yet. Look at: cd langfuse/app && docker compose logs --tail 50 langfuse-web" >&2; exit 1; }

get() { grep -E "^$1=" app/.env | cut -d= -f2-; }
cat <<MSG

Langfuse is ready: http://127.0.0.1:3002
  Email    : $(get LANGFUSE_INIT_USER_EMAIL)
  Password : $(get LANGFUSE_INIT_USER_PASSWORD)
  (everything is in the hidden file langfuse/app/.env)

API keys of the project "$(get LANGFUSE_INIT_PROJECT_NAME)" (for Open WebUI and Hermes):
  Public key : $(get LANGFUSE_INIT_PROJECT_PUBLIC_KEY)
  Secret key : $(get LANGFUSE_INIT_PROJECT_SECRET_KEY)
  Address from the other containers: http://langfuse-web:3000
MSG
