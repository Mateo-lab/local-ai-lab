#!/usr/bin/env bash
# Generates the client computer's SSH configuration (Windows, macOS or Linux) from lab.conf.
#
#   lab client            writes windows/ssh_config_aibeast.txt and shows the steps to follow
#   lab client --print    only prints the configuration block (nothing is written)
#
# The block defines the "aibeast" shortcut (used by every script in windows/) and the tunnels
# to all the interfaces, plus the remote desktop (RDP). Nothing is opened on the network:
# the interfaces stay bound to 127.0.0.1 on the AI machine, the tunnels go through SSH.
# See docs/remote-access.md.
set -euo pipefail
ROOT="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/.." && pwd)"
if [ -f "$ROOT/lab.conf" ]; then . "$ROOT/lab.conf"; fi

HOST="${LAB_HOST:-}"
USER_="${LAB_USER:-${USER:-$(id -un)}}"
PORT="${LAB_SSH_PORT:-22}"
KEY="${LAB_SSH_KEY:-~/.ssh/id_ed25519}"
RDP="${LAB_RDP_LOCAL_PORT:-13389}"

if [ -z "$HOST" ]; then
  cat >&2 <<EOF
lab client: LAB_HOST is not set.
  1. cp lab.conf.example lab.conf   (if not done yet)
  2. in lab.conf, set the address your PC uses to reach this machine, for example:
       LAB_HOST=192.168.1.50
     Addresses of this machine:
$(hostname -I 2>/dev/null | tr ' ' '\n' | grep -v '^$' | sed 's/^/       /')
  3. run again: lab client
EOF
  exit 1
fi
case "$HOST$USER_$PORT$KEY$RDP" in *[[:space:]\"\'\;\&\|\`\$]*) echo "lab client: invalid value in lab.conf (space or special character)" >&2; exit 1 ;; esac
[[ "$PORT" =~ ^[0-9]+$ && "$RDP" =~ ^[0-9]+$ ]] || { echo "lab client: LAB_SSH_PORT and LAB_RDP_LOCAL_PORT must be numbers" >&2; exit 1; }

bloc() {
cat <<EOF
# SSH shortcut to the AI machine (generated by "lab client" on $(date +%Y-%m-%d)).
# ADD it at the end of your SSH configuration file:
#   Windows: %USERPROFILE%\\.ssh\\config      macOS / Linux: ~/.ssh/config
# Create the file if it does not exist. Then: ssh aibeast
Host aibeast
  HostName $HOST
  Port $PORT
  User $USER_
  IdentityFile $KEY
  ServerAliveInterval 30
  ServerAliveCountMax 3
  ExitOnForwardFailure yes
  # Tunnels reachable from THIS PC only (never from its network), even if GatewayPorts is enabled elsewhere
  GatewayPorts no
  # Portal (home page) and button panel
  LocalForward 127.0.0.1:3010 127.0.0.1:3010
  LocalForward 127.0.0.1:3011 127.0.0.1:3011
  # Interfaces: Open WebUI, n8n, Qdrant, ComfyUI
  LocalForward 127.0.0.1:3000 127.0.0.1:3000
  LocalForward 127.0.0.1:5678 127.0.0.1:5678
  LocalForward 127.0.0.1:6333 127.0.0.1:6333
  LocalForward 127.0.0.1:8188 127.0.0.1:8188
  # Observability: Grafana, Prometheus, Langfuse
  LocalForward 127.0.0.1:3001 127.0.0.1:3001
  LocalForward 127.0.0.1:9090 127.0.0.1:9090
  LocalForward 127.0.0.1:3002 127.0.0.1:3002
  # Notifications (ntfy), Alertmanager, OpenClaw
  LocalForward 127.0.0.1:2586 127.0.0.1:2586
  LocalForward 127.0.0.1:9093 127.0.0.1:9093
  LocalForward 127.0.0.1:18789 127.0.0.1:18789
  # Hermes Desktop graphical interface (only carries traffic when "lab gateway" is running; harmless otherwise)
  LocalForward 127.0.0.1:9119 127.0.0.1:9119
  # Remote desktop (RDP): on your PC, connect to 127.0.0.1:$RDP
  LocalForward 127.0.0.1:$RDP 127.0.0.1:3389
EOF
}

if [ "${1:-}" = "--print" ]; then bloc; exit 0; fi

OUT="$ROOT/windows/ssh_config_aibeast.txt"
bloc | sed 's/$/\r/' > "$OUT"     # Windows line endings: the file opens cleanly in Notepad
echo "Written: $OUT  (ignored by git: it contains your address)"
echo
bloc
cat <<EOF

─── Steps on your PC (details: docs/remote-access.md) ──────────────────────────────
1. Create a key, if you do not have one:    ssh-keygen -t ed25519
2. Copy the PUBLIC key to this machine (the account password is asked one last time):
   Windows (PowerShell):
     type \$env:USERPROFILE\\.ssh\\id_ed25519.pub | ssh -p $PORT $USER_@$HOST "mkdir -p ~/.ssh && chmod 700 ~/.ssh && cat >> ~/.ssh/authorized_keys && chmod 600 ~/.ssh/authorized_keys"
   macOS / Linux:
     ssh-copy-id -p $PORT $USER_@$HOST
3. Add the block above at the end of the PC's SSH configuration file
   (on Windows: windows\\outils\\Installer-config-SSH.bat does it for you).
4. Test:  ssh aibeast  → must connect WITHOUT asking for the account password.
5. Open the tunnels:  ssh -N aibeast  (or windows\\outils\\Ouvrir-AiBeast.bat), then http://127.0.0.1:3010
EOF
